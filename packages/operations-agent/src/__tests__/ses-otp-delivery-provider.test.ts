// ─── AC-007: OTP format — 100 samples, all exactly 6 digits ──────────────────

describe("generateOtp — AC-007: 6-digit format invariant", () => {
  it("generates 100 OTPs that are all exactly 6 digits (000000–999999)", () => {
    const otps = Array.from({ length: 100 }, () => generateOtp());
    for (const otp of otps) {
      expect(otp).toMatch(/^\d{6}$/, `OTP '${otp}' is not exactly 6 digits`);
      const n = parseInt(otp, 10);
      expect(n).toBeGreaterThanOrEqual(0);
      expect(n).toBeLessThanOrEqual(999999);
    }
  });

  it("leading zeros are preserved (padStart(6, '0'))", () => {
    // We cannot force a specific value but we can verify the format contract
    // by checking that the string representation is always 6 chars wide.
    const otps = Array.from({ length: 100 }, () => generateOtp());
    for (const otp of otps) {
      expect(otp).toHaveLength(6);
    }
  });
});

// ─── SI-001: CSPRNG verification ─────────────────────────────────────────────

describe("generateOtp — SI-001: CSPRNG (not Math.random())", () => {
  it("produces a uniform-ish distribution over 1000 samples (Math.random() would cluster)", () => {
    // This test cannot distinguish crypto.randomBytes from Math.random() via statistics alone
    // with only 1000 samples. However it documents the intent and catches a completely broken
    // implementation (e.g. always returning the same value).
    const seen = new Set<string>();
    for (let i = 0; i < 1000; i++) {
      seen.add(generateOtp());
    }
    // With a CSPRNG over 1,000,000 values, 1000 samples should yield close to 1000 unique values.
    // Even a very bad RNG would produce > 900 unique values in 1000 draws from 1M possibilities.
    expect(seen.size).toBeGreaterThan(900);
  });
});

// ─── SI-002: Email address never in logs ─────────────────────────────────────

describe("SesOtpDeliveryProvider — SI-002: domain-only logging", () => {
  it("never logs the full email address — only the domain portion", async () => {
    const fullEmail = "secret.user@private-domain.com";
    const sendMock = makeSendMock({ MessageId: "msg-id" });
    const sesClient = buildFakeClient(sendMock);
    const logger = makeLogger();

    const provider = new SesOtpDeliveryProvider({
      sesClient,
      fromAddress: "noreply@cello.example.com",
      logger,
    });

    await provider.sendOtp(fullEmail, "123456");

    // Collect all stringified log call arguments
    const allLoggedStrings = [
      ...logger.infoCalls.map((c) => JSON.stringify(c)),
      ...logger.errorCalls.map((c) => JSON.stringify(c)),
    ].join(" ");

    expect(allLoggedStrings).not.toContain(fullEmail);
    expect(allLoggedStrings).not.toContain("secret.user");
    expect(allLoggedStrings).toContain("private-domain.com");
  });

  it("does not log full email on bounce either", async () => {
    const fullEmail = "bounce.secret@private-domain.net";
    const bounceError = Object.assign(new Error("blacklisted"), { name: "MessageRejected" });
    const sendMock = vi.fn().mockRejectedValue(bounceError);
    const sesClient = buildFakeClient(sendMock);
    const logger = makeLogger();

    const provider = new SesOtpDeliveryProvider({
      sesClient,
      fromAddress: "noreply@cello.example.com",
      logger,
    });

    await provider.sendOtp(fullEmail, "654321").catch(() => undefined);

    const allLoggedStrings = [
      ...logger.infoCalls.map((c) => JSON.stringify(c)),
      ...logger.errorCalls.map((c) => JSON.stringify(c)),
    ].join(" ");

    expect(allLoggedStrings).not.toContain(fullEmail);
    expect(allLoggedStrings).not.toContain("bounce.secret");
  });
});

