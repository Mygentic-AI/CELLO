/**
 * ses-otp-delivery-provider.test.ts — Unit tests for SesOtpDeliveryProvider.
 *
 * Specification (SPARC Phase S):
 *
 * AC-001: SES accepts delivery — MessageId returned; otp.delivery.sent logged at INFO
 *         with { emailDomain, messageId, correlationId }. Subject = 'Your CELLO verification code'.
 *         (Full integration test guarded by SES_INTEGRATION_TEST=true — AC-008.)
 *
 * AC-002: 6th sendOtp() within 1 hour throws RateLimitError before any SES call.
 *         Rate limit is per email address, per provider instance.
 *
 * AC-003: Rate limit counter resets after the 1-hour rolling window expires.
 *         After reset, the 1st send in the new window succeeds.
 *
 * AC-004: SES hard bounce → DeliveryError with sesErrorType='Bounce';
 *         otp.delivery.failed logged at ERROR with { emailDomain, sesErrorType, correlationId }.
 *         Second sendOtp() with the same bounced address returns immediate DeliveryError
 *         without calling SES.
 *
 * AC-005: SES throttling → 1-second wait → retry once.
 *         If retry succeeds: otp.delivery.retried logged at INFO with { emailDomain,
 *           retryDelayMs: 1000, correlationId }.
 *         If retry also fails: DeliveryError thrown.
 *
 * AC-006: ConsoleOtpDeliveryProvider prints OTP to stdout; no network call made.
 *         (ConsoleOtpDeliveryProvider already exists — verified with a quick smoke test.)
 *
 * AC-007: 100 OTPs generated by generateOtp() are all exactly 6 digits (000000–999999).
 *         Leading zeros preserved.
 *
 * SI-001: generateOtp() uses crypto CSPRNG (randomBytes), not Math.random().
 *         Verified by observing uniform distribution over 1000 samples.
 *
 * SI-002: Full email address never appears in any log call — only emailDomain.
 *         Unit test scans all log.info/error calls for the full address string.
 *
 * SI-003: SES client injected via constructor — provider never constructs its own.
 *         Unit test asserts the exact client instance passed in is used.
 */

